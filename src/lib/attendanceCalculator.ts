export interface Period {
  startDate: string;
  endDate: string;
}

export type AttendanceType = "fixed" | "flexible" | "remote";

export type CalendarPatternType =
  | "SINGLE_DATE"
  | "DATE_RANGE"
  | "RECURRING_WEEKLY";

export type CalendarEffectType = "FULL_DAY_OFF" | string;

export interface CalendarRule {
  title: string;
  year: number;

  patternType: CalendarPatternType;
  effectType: CalendarEffectType;

  startDate?: string;
  endDate?: string;

  startTime?: string;
  endTime?: string;

  daysOfWeek?: string[];
  dayOfMonth?: number;
  repeatEvery?: number;

  isAutoGenerated?: boolean;
}

export interface AttendanceLocation {
  _id?: string;
  name?: string;
  timezone?: string;
  latitude?: number;
  longitude?: number;
  radius?: number;
}

export interface GroupSettings {
  _id?: string;

  groupName?: string;
  latinName?: string;

  companyId?: string;

  attendanceType: AttendanceType;

  offDays?: string[];

  calendarRules?: CalendarRule[];

  locationId?: AttendanceLocation | null;

  standardMonthlyHours?: number;

  severeLateAfter?: number;

  fixedAttendance?: {
    startTime?: string;
    endTime?: string;

    breakFrom?: string;
    breakTo?: string;

    earlyIn?: number;
    earlyOut?: number;
    overtime?: number;
  };

  flexibleAttendance?: {
    requiredHoursPerDay?: number;
  };

  remoteAttendance?: {
    requiredHoursPerDay?: number;
  };
}

