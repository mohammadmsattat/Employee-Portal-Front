const getAttendanceType = (group: GroupSettings): AttendanceType => {
  return group.attendanceType || "fixed";
};

/* =========================================================
   Calendar Rules
========================================================= */

const isFullDayOffRule = (rule: CalendarRule): boolean => {
  return rule.effectType === "FULL_DAY_OFF";
};

const matchesSingleDateRule = (date: string, rule: CalendarRule): boolean => {
  if (rule.patternType !== "SINGLE_DATE") {
    return false;
  }

  if (!rule.startDate) {
    return false;
  }

  return date === rule.startDate;
};

const matchesDateRangeRule = (date: string, rule: CalendarRule): boolean => {
  if (rule.patternType !== "DATE_RANGE") {
    return false;
  }

  if (!rule.startDate || !rule.endDate) {
    return false;
  }

  return isDateBetween(date, rule.startDate, rule.endDate);
};

const matchesRecurringWeeklyRule = (
  date: string,
  rule: CalendarRule,
): boolean => {
  if (rule.patternType !== "RECURRING_WEEKLY") {
    return false;
  }

  if (!rule.startDate) {
    return false;
  }

  if (!isDateBetween(date, rule.startDate, rule.endDate)) {
    return false;
  }

  const dateDayName = normalizeDayName(getDayName(date));

  const ruleDays = (rule.daysOfWeek ?? []).map(normalizeDayName);

  if (!ruleDays.includes(dateDayName)) {
    return false;
  }

  const repeatEvery = Math.max(1, rule.repeatEvery ?? 1);

  if (repeatEvery === 1) {
    return true;
  }

  const start = createLocalDate(rule.startDate);

  const current = createLocalDate(date);

  const differenceInDays = Math.floor(
    (current.getTime() - start.getTime()) / (1000 * 60 * 60 * 24),
  );

  if (differenceInDays < 0) {
    return false;
  }

  const weeks = Math.floor(differenceInDays / 7);

  return weeks % repeatEvery === 0;
};

const calendarRuleMatchesDate = (date: string, rule: CalendarRule): boolean => {
  if (!isFullDayOffRule(rule)) {
    return false;
  }

  switch (rule.patternType) {
    case "SINGLE_DATE":
      return matchesSingleDateRule(date, rule);

    case "DATE_RANGE":
      return matchesDateRangeRule(date, rule);

    case "RECURRING_WEEKLY":
      return matchesRecurringWeeklyRule(date, rule);

    default:
      return false;
  }
};

const getDayOffCalendarRule = (
  date: string,
  group: GroupSettings,
): CalendarRule | undefined => {
  return (group.calendarRules ?? []).find((rule) =>
    calendarRuleMatchesDate(date, rule),
  );
};

/* =========================================================
   Working Day
========================================================= */

const isConfiguredOffDay = (date: string, group: GroupSettings): boolean => {
  const dayName = normalizeDayName(getDayName(date));

  const offDays = (group.offDays ?? []).map(normalizeDayName);

  return offDays.includes(dayName);
};

const isWorkingDay = (date: string, group: GroupSettings): boolean => {
  /*
   * Explicit calendar rules have priority.
   */
  if (getDayOffCalendarRule(date, group)) {
    return false;
  }

  /*
   * Weekly off days.
   */
  if (isConfiguredOffDay(date, group)) {
    return false;
  }

  return true;
};

const isHoliday = (date: string, group: GroupSettings): boolean => {
  return Boolean(getDayOffCalendarRule(date, group));
};

/* =========================================================
   Fixed Attendance
========================================================= */

const getFixedStartTime = (group: GroupSettings): string => {
  return group.fixedAttendance?.startTime || DEFAULT_FIXED_START;
};

const getFixedEndTime = (group: GroupSettings): string => {
  return group.fixedAttendance?.endTime || DEFAULT_FIXED_END;
};

const getLateGraceMinutes = (group: GroupSettings): number => {
  return Math.max(0, group.fixedAttendance?.earlyIn ?? 0);
};

/* =========================================================
   Required Hours
========================================================= */

const getRequiredHours = (group: GroupSettings): number => {
  switch (group.attendanceType) {
    case "fixed": {
      const start = toMinutes(getFixedStartTime(group));

      const end = toMinutes(getFixedEndTime(group));

      let minutes = end - start;

      const breakFrom = group.fixedAttendance?.breakFrom;

      const breakTo = group.fixedAttendance?.breakTo;

      if (breakFrom && breakTo) {
        const breakMinutes = toMinutes(breakTo) - toMinutes(breakFrom);

        if (breakMinutes > 0) {
          minutes -= breakMinutes;
        }
      }

      return Math.max(0, minutes / 60);
    }

    case "flexible":
      return Math.max(0, group.flexibleAttendance?.requiredHoursPerDay ?? 0);

    case "remote":
      return Math.max(0, group.remoteAttendance?.requiredHoursPerDay ?? 0);

    default:
      return 0;
  }
};

/* =========================================================
   Break
========================================================= */

const calculateOverlapMinutes = (
  start1: number,
  end1: number,
  start2: number,
  end2: number,
): number => {
  const start = Math.max(start1, start2);

  const end = Math.min(end1, end2);

  return Math.max(0, end - start);
};

/* =========================================================
   Worked Minutes
========================================================= */

const calculateWorkedMinutes = (
  date: string,
  records: FingerprintRecord[],
  group: GroupSettings,
): number => {
  if (!records.length) {
    return 0;
  }

  const sortedRecords = [...records].sort(
    (a, b) => toMinutes(a.Time) - toMinutes(b.Time),
  );

  const timezone = group.locationId?.timezone || DEFAULT_TIMEZONE;

  const today = getTodayDate(timezone);

  let workedMinutes = 0;

  let openCheckIn: number | null = null;

  /*
   * Calculate check-in / check-out sessions.
   */
  for (const record of sortedRecords) {
    const recordMinutes = toMinutes(record.Time);

    if (record.type === "Check-in") {
      if (openCheckIn === null) {
        openCheckIn = recordMinutes;
      }

      continue;
    }

    if (record.type === "Check-out" && openCheckIn !== null) {
      const difference = recordMinutes - openCheckIn;

      if (difference > 0) {
        workedMinutes += difference;
      }

      openCheckIn = null;
    }
  }

  /*
   * Open session.
   */
  if (openCheckIn !== null) {
    let endMinutes: number | null = null;

    if (date === today) {
      endMinutes = getCurrentMinutes(timezone);
    } else if (group.attendanceType === "fixed") {
      endMinutes = toMinutes(getFixedEndTime(group));
    }

    if (endMinutes !== null && endMinutes > openCheckIn) {
      workedMinutes += endMinutes - openCheckIn;
    }
  }

  /*
   * Remove fixed break from actual
   * worked time.
   */
  if (
    group.attendanceType === "fixed" &&
    group.fixedAttendance?.breakFrom &&
    group.fixedAttendance?.breakTo
  ) {
    const breakFrom = toMinutes(group.fixedAttendance.breakFrom);

    const breakTo = toMinutes(group.fixedAttendance.breakTo);

    if (breakTo > breakFrom) {
      let correctedMinutes = 0;

      let sessionStart: number | null = null;

      for (const record of sortedRecords) {
        const time = toMinutes(record.Time);

        if (record.type === "Check-in") {
          if (sessionStart === null) {
            sessionStart = time;
          }

          continue;
        }

        if (record.type === "Check-out" && sessionStart !== null) {
          if (time > sessionStart) {
            const sessionMinutes = time - sessionStart;

            const breakOverlap = calculateOverlapMinutes(
              sessionStart,
              time,
              breakFrom,
              breakTo,
            );

            correctedMinutes += Math.max(0, sessionMinutes - breakOverlap);
          }

          sessionStart = null;
        }
      }

      /*
       * Still-open session.
       */
      if (sessionStart !== null) {
        let sessionEnd: number | null = null;

        if (date === today) {
          sessionEnd = getCurrentMinutes(timezone);
        } else if (group.attendanceType === "fixed") {
          sessionEnd = toMinutes(getFixedEndTime(group));
        }

        if (sessionEnd !== null && sessionEnd > sessionStart) {
          const sessionMinutes = sessionEnd - sessionStart;

          const breakOverlap = calculateOverlapMinutes(
            sessionStart,
            sessionEnd,
            breakFrom,
            breakTo,
          );

          correctedMinutes += Math.max(0, sessionMinutes - breakOverlap);
        }
      }

      workedMinutes = Math.max(0, correctedMinutes);
    }
  }

  return workedMinutes;
};

/* =========================================================
   Late
========================================================= */

const calculateLate = (
  firstCheckInTime: string | undefined,
  group: GroupSettings,
): {
  late: boolean;
  lateMinutes: number;
} => {
  if (group.attendanceType !== "fixed" || !firstCheckInTime) {
    return {
      late: false,
      lateMinutes: 0,
    };
  }

  const startMinutes = toMinutes(getFixedStartTime(group));

  const checkInMinutes = toMinutes(firstCheckInTime);

  const gracePeriod = getLateGraceMinutes(group);

  const allowedStart = startMinutes + gracePeriod;

  if (checkInMinutes <= allowedStart) {
    return {
      late: false,
      lateMinutes: 0,
    };
  }

  return {
    late: true,

    /*
     * Actual minutes late from scheduled
     * start time.
     */
    lateMinutes: checkInMinutes - startMinutes,
  };
};

/* =========================================================
   Daily
========================================================= */

const processDailyRecords = (
  date: string,
  records: FingerprintRecord[],
  group: GroupSettings,
): DailyAttendance => {
  const sortedRecords = [...records].sort(
    (a, b) => toMinutes(a.Time) - toMinutes(b.Time),
  );

  const workingDay = isWorkingDay(date, group);

  const holiday = isHoliday(date, group);

  const attendanceType = getAttendanceType(group);

  const requiredHours = getRequiredHours(group);

  const checkIns = sortedRecords.filter((record) => record.type === "Check-in");

  const checkOuts = sortedRecords.filter(
    (record) => record.type === "Check-out",
  );

  const hasCheckIn = checkIns.length > 0;

  const hasCheckOut = checkOuts.length > 0;

  const firstCheckIn = checkIns[0];

  const lastCheckOut =
    checkOuts.length > 0 ? checkOuts[checkOuts.length - 1] : undefined;

  /*
   * NON-WORKING DAY
   *
   * If the day is an additional calendar holiday
   * and the employee has a Check-in,
   * count it as an extra worked day.
   *
   * Weekly off days are NOT counted as extra
   * worked days because holiday is false for them.
   */
  if (!workingDay) {
    const isExtraWorkedDay = holiday && hasCheckIn;

    const workedMinutes = isExtraWorkedDay
      ? calculateWorkedMinutes(date, sortedRecords, group)
      : 0;

    const workedHours = minutesToHours(workedMinutes);

    const warnings: string[] = [];

    if (isExtraWorkedDay && !hasCheckOut) {
      warnings.push("Missing check-out record");
    }

    return {
      date,

      isWorkingDay: false,

      isWorked: false,

      isAbsent: false,

      isHoliday: holiday,

      isExtraWorkedDay,

      firstCheckIn: isExtraWorkedDay ? firstCheckIn?.Time : undefined,

      lastCheckOut: isExtraWorkedDay ? lastCheckOut?.Time : undefined,

      late: false,

      lateMinutes: 0,

      workedHours,

      requiredHours,

      hoursCompleted: isExtraWorkedDay
        ? requiredHours <= 0 || workedHours >= requiredHours
        : false,

      attendanceType,

      records: sortedRecords,

      warnings,
    };
  }

  const workedMinutes = calculateWorkedMinutes(date, sortedRecords, group);

  const workedHours = minutesToHours(workedMinutes);

  /*
   * Worked day:
   * At least one Check-in.
   */
  const isWorked = hasCheckIn;

  /*
   * Absent day:
   * Working day with no Check-in.
   */
  const isAbsent = !hasCheckIn;

  const lateResult = calculateLate(firstCheckIn?.Time, group);

  const hoursCompleted =
    requiredHours <= 0 ? isWorked : workedHours >= requiredHours;

  const warnings: string[] = [];

  if (isWorked && !hasCheckOut) {
    warnings.push("Missing check-out record");
  }

  if (lateResult.late) {
    warnings.push(`Late arrival by ${lateResult.lateMinutes} minutes`);
  }

  if (
    isWorked &&
    (attendanceType === "flexible" || attendanceType === "remote") &&
    requiredHours > 0 &&
    workedHours < requiredHours
  ) {
    warnings.push(
      `Required ${requiredHours} hours, worked ${workedHours.toFixed(2)} hours`,
    );
  }

  return {
    date,

    isWorkingDay: true,

    isWorked,

    isAbsent,

    isHoliday: holiday,

    isExtraWorkedDay: false,

    firstCheckIn: firstCheckIn?.Time,

    lastCheckOut: lastCheckOut?.Time,

    late: lateResult.late,

    lateMinutes: lateResult.lateMinutes,

    workedHours,

    requiredHours,

    hoursCompleted,

    attendanceType,

    records: sortedRecords,

    warnings,
  };
};

/* =========================================================
   Calculate Summary
========================================================= */

const calculate = (
  period: Period,
  group: GroupSettings,
  records: FingerprintRecord[],
): AttendanceSummary | null => {
  if (!group) {
    return null;
  }

  if (!period.startDate || !period.endDate) {
    return null;
  }

  if (period.startDate > period.endDate) {
    return null;
  }

  /*
   * Generate every date inside
   * the requested period.
   */
  const allDates = getDateRange(period.startDate, period.endDate);

  /*
   * Group fingerprints by date.
   */
  const recordsByDate = new Map<string, FingerprintRecord[]>();

  for (const record of records) {
    if (!record.date) {
      continue;
    }

    const existing = recordsByDate.get(record.date) ?? [];

    existing.push(record);

    recordsByDate.set(record.date, existing);
  }

  /*
   * Process every calendar date,
   * including dates with no records.
   *
   * This is important for Absent Days
   * and Extra Worked Days.
   */
  const dailyDetails = allDates.map((date) =>
    processDailyRecords(date, recordsByDate.get(date) ?? [], group),
  );

  const timezone = group.locationId?.timezone || DEFAULT_TIMEZONE;

  const today = getTodayDate(timezone);

  /*
   * Only working days that have
   * already elapsed participate
   * in attendance KPIs.
   *
   * Future working days are NOT absent.
   */
  const elapsedWorkingDays = dailyDetails.filter(
    (day) => day.isWorkingDay && day.date <= today,
  );

  /*
   * Worked Days
   */
  const workedDays = elapsedWorkingDays.filter((day) => day.isWorked);

  /*
   * Absent Days
   */
  const absentDays = elapsedWorkingDays.filter((day) => day.isAbsent);

  /*
   * Late Arrivals
   */
  const lateArrivals = elapsedWorkingDays.filter((day) => day.late);

  /*
   * Total calendar days
   */
  const totalCalendarDays = allDates.length;

  /*
   * Total elapsed working days
   */
  const totalWorkingDays = elapsedWorkingDays.length;

  /*
   * Holidays + weekly off days
   */
  const totalNonWorkingDays = dailyDetails.filter(
    (day) => !day.isWorkingDay,
  ).length;

  /*
   * Extra Worked Days
   *
   * Count only days that:
   * 1. Are additional calendar holidays.
   * 2. Have at least one Check-in.
   *
   * Weekly off days are excluded.
   */
  const extraWorkedDays = dailyDetails.filter(
    (day) => day.isExtraWorkedDay,
  ).length;

  return {
    totalCalendarDays,

    totalWorkingDays,

    totalNonWorkingDays,

    workedDays: workedDays.length,

    absentDays: absentDays.length,

    lateArrivals: lateArrivals.length,

    extraWorkedDays,

    dailyDetails,
  };
};

/* =========================================================
   Get Day Details
========================================================= */

const getDayDetails = (
  date: string,
  group: GroupSettings,
  records: FingerprintRecord[],
): DailyAttendance | null => {
  if (!group) {
    return null;
  }

  const dayRecords = records.filter((record) => record.date === date);

  return processDailyRecords(date, dayRecords, group);
};

